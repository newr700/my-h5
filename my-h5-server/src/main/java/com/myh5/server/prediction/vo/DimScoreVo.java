package com.myh5.server.prediction.vo;

/**
 * 六维雷达图的一个顶点（VO）。
 *
 * 草图上「这个六边形，要可调数字显示」—— 所以分数必须随数据下发，
 * 而不是让前端按固定刻度画一个好看的图形。
 *
 * 【为什么要带 label 而不是只给 key】
 * 让后端决定「有哪六个维度、叫什么名字、按什么顺序摆在六边形上」：
 * 维度调整（比如把「对位优势」换成「伤病情况」）只改后端一处，
 * 前端只是照着画。如果顺序和名称写在两处，早晚会出现「后端加了第七维、
 * 前端还是六边形」这种对不上的状态。
 */
public record DimScoreVo(
        /** 维度键，前端用它做 :key 与样式区分，如 history */
        String key,
        /** 维度显示名，如「历史夺冠次数」 */
        String label,
        /** 0~100 的分数 */
        int score
) {
}
