-- 【关于文档头条「夺冠总次数」的一处数据质量说明】
--   文档头条写「曼联 13 / 曼城 7」，但其逐年列表实算曼联 14 次、曼城 8 次，
--   且漏列了利物浦（2 次）。本迁移以「逐年列表」为权威源插入，
--   因此现算出的夺冠次数会是 曼联14/曼城8/切尔西5/阿森纳3/利物浦2/布莱克本1/莱斯特城1，
--   与表格自洽，也比文档头条更准确。
--
-- 【兼容性】同此前各版：只用 MySQL 8 与 H2（MySQL 模式）都支持的写法。
-- ============================================================

