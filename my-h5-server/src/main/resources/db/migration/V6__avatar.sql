-- ============================================================
-- V6 用户头像
-- ------------------------------------------------------------
-- 【设计决策】头像文件本身存在磁盘（见 WebMvcConfig 把 /uploads/** 映射为本地目录），
-- 数据库只存一个【相对路径】（如 /uploads/12_1690000000000.png），不存二进制。
-- 理由：大文件进库会撑爆行、拖慢查询、备份变慢 —— 库里只存“指针”是通用规范。
--
-- 【兼容性】与 V1 同样的约定：只用 MySQL 8 和 H2（MySQL 模式）都支持的写法。
--   VARCHAR(512) 足够容纳长路径；DEFAULT NULL 兼容老用户（NULL = 没设头像，
--   前端显示首字母占位，与现在的行为一致，不破坏存量数据）。
-- ============================================================

ALTER TABLE app_user ADD COLUMN avatar_url VARCHAR(512) DEFAULT NULL
    COMMENT '头像相对路径，如 /uploads/12_1690000000000.png；NULL 表示未设置（前端显示首字母占位）';
