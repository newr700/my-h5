-- ============================================================
-- V3 【V2 第一步：防超卖】给比赛表加库存模型
-- ------------------------------------------------------------
-- 【这一步解决什么】
-- V1 建的 match_info 只有「价格」，没有「票数」。也就是说同一场比赛可以被无限下单 ——
-- 票卖出去了，可座位数量却从不减少。这就是「超卖」，
-- 在票务 / 电商系统里属于一票否决级事故（钱收了，货没有）。
--
-- 【为什么新增 V3，而不是回头改 V1】
-- Flyway 会给每个执行过的脚本记校验和，改动老脚本会导致启动时
-- 「校验和不匹配」直接拒绝启动。所以【新增需求 = 新增版本脚本】，
-- 这是数据库变更纪律里最硬的一条（工程手册第 7 章）。
-- 现实项目上线后加字段，也是这么加的。
--
-- 【兼容性】同 V1/V2：只用 MySQL 8 与 H2（MySQL 模式）都支持的写法，
-- 因为单元测试会在 H2 上执行同一份脚本（见 src/test/resources）。
-- ============================================================

-- ─────────────────────────────────────────────────────────────
-- 库存为什么要【两列】：total_stock 和 stock
-- ─────────────────────────────────────────────────────────────
-- 只留「剩余 stock」也足以防超卖，但那样产品永远不知道「这场上座多少、总共放了多少票」，
-- 而票务页面上「已售 380 / 共 500」是必备信息。
-- 注意「已售多少」【没有】单独存一列 —— 它能由 total_stock - stock 算出来。
--
-- （技能点：为什么不多存一个 sold 列）
-- 能算出来的值就不要冗余存储。每多存一份派生数据，就等于多了一条
-- 「两个数字必须永远相等」的不变量；这类不变量在并发下迟早会被破坏：
-- 改了 stock 忘了改 sold，两边就永久对不上，而且极难排查是从哪一次请求开始错的。
-- 这是「用冗余换取查询便利」与「引入一致性风险」之间的经典取舍，这里选后者让路。
ALTER TABLE match_info ADD COLUMN total_stock INT NOT NULL DEFAULT 0 COMMENT '总票数';
ALTER TABLE match_info ADD COLUMN stock      INT NOT NULL DEFAULT 0 COMMENT '剩余票数（并发扣减的热点列）';

-- ─────────────────────────────────────────────────────────────
-- 回填存量数据
-- ─────────────────────────────────────────────────────────────
-- 每场比赛放 500 张票（MVP 阶段的合理假设值，真实项目应由运营配置）。
UPDATE match_info SET total_stock = 500;

-- 剩余票数 = 总数 - 已支付订单占用的票数
UPDATE match_info SET stock = total_stock - COALESCE(
    (SELECT SUM(o.quantity) FROM match_order o
      WHERE o.match_id = match_info.id AND o.status = 'paid'), 0);

-- 【诚实说明这两条回填语句的边界】
-- 上面按「已支付订单」扣减，是因为本项目【下单时就扣库存】，
-- pending 订单的占用会在 15 分钟未支付（或用户取消）时回补，属于短期占用。
-- 但如果线上跑这套迁移时，库里已经存在大量 pending 订单，
-- 严格做法应当把 pending 也算进占用（否则这部分票被重复卖出）。
-- 真实项目的回填口径必须对齐业务的扣减时机 ——
-- 「迁移脚本的口径和代码逻辑不一致」是数据迁移事故的经典来源。
--
-- COALESCE 的作用：该比赛还没有任何订单时 SUM 返回 NULL，
-- 而 NULL 参与算术会得到 NULL，导致整列变 NULL，
-- 之后下单的 `WHERE stock >= qty` 判断会因为 NULL 而恒不成立（订单永远下不了）。
-- 「NULL 参与运算」是 SQL 里最隐蔽的一类 bug。
