-- ============================================================
-- V4 【V2 第二步：幂等 / 防重复下单】
-- ------------------------------------------------------------
-- 【解决什么】
-- 用户连点、前端重试、网络抖动，都可能让「同一笔下单请求」到达后端多次。
-- 若每次都新建订单，用户会重复扣钱扣票 —— 比超卖更常见、更隐蔽的资损。
--
-- 【方案】
-- 1) 前端在「一笔下单意图」开始时生成一个 requestId（幂等号），失败保留、成功清空；
-- 2) 订单表新增 request_id 列，并建 (user_id, request_id) 唯一索引；
-- 3) 后端下单前先按 (userId, requestId) 查：命中就返回原订单（不重复扣库存）；
--    唯一索引作为并发兜底，保证两个相同 requestId 绝不会建出两笔订单。
-- 这是「客户端生成幂等号 + 服务端唯一约束」的经典组合。
--
-- 【为什么 request_id 设可空而不是 NOT NULL】
-- 库里已存在 V1/V2/V3 阶段的老订单，它们没有 request_id；
-- 若设 NOT NULL 并给默认值 ''，同一用户的多笔老订单会撞 (user_id, '') 唯一索引，导致建索引失败。
-- 设可空后，老数据全是 NULL，唯一索引允许重复的 NULL（MySQL 与 H2 均遵循 SQL 标准），建索引安全。
-- 非空约束改由应用层 @NotBlank 兜底（见 CreateOrderRequest），两层保险。
--
-- 【兼容性】同 V1/V2/V3：只用 MySQL 8 与 H2（MySQL 模式）都支持的写法，
-- 因为单元测试会在 H2 上执行同一份迁移（见 src/test/resources）。
-- ============================================================

ALTER TABLE match_order ADD COLUMN request_id VARCHAR(64) COMMENT '幂等号：客户端生成，同一笔重试用同一号';
CREATE UNIQUE INDEX uk_match_order_request ON match_order(user_id, request_id);
